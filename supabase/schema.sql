create or replace function chat_private.chat_enqueue_storage_delete(url text)
returns void language plpgsql security definer set search_path = '' as $$
declare m text[];
begin
  if url is null then return; end if;
  m := regexp_match(url, '/storage/v1/object/(?:public|sign)/([^/]+)/([^?]+)');
  if m is null then return; end if;
  if exists (select 1 from public.chat_messages x where x.attachment_url = url and x.deleted_at is null)
     or exists (select 1 from public.chat_group_messages x where x.attachment_url = url and x.deleted_at is null)
     or exists (select 1 from public.chat_statuses x where x.media_url = url) then
    return;
  end if;
  insert into public.chat_storage_cleanup_queue (bucket, path) values (m[1], m[2]);
end; $$;
