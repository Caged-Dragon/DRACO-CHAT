create or replace function chat_private.chat_enforce_rate_limit()
returns trigger language plpgsql security definer set search_path = '' as $$
declare recent int;
begin
  if auth.uid() is null then return new; end if;
  if tg_table_name = 'chat_messages' then
    select count(*) into recent from public.chat_messages where sender_id = new.sender_id and created_at > now() - interval '10 seconds';
    if recent >= 20 then raise exception 'You are sending messages too fast. Please slow down.' using errcode = 'P0001'; end if;
  elsif tg_table_name = 'chat_group_messages' then
    select count(*) into recent from public.chat_group_messages where sender_id = new.sender_id and created_at > now() - interval '10 seconds';
    if recent >= 20 then raise exception 'You are sending messages too fast. Please slow down.' using errcode = 'P0001'; end if;
  elsif tg_table_name = 'chat_friendships' then
    select count(*) into recent from public.chat_friendships where requester_id = new.requester_id and created_at > now() - interval '1 hour';
    if recent >= 30 then raise exception 'Too many friend requests. Please try again later.' using errcode = 'P0001'; end if;
  elsif tg_table_name = 'chat_reports' then
    select count(*) into recent from public.chat_reports where reporter_id = new.reporter_id and created_at > now() - interval '1 day';
    if recent >= 20 then raise exception 'Too many reports submitted today.' using errcode = 'P0001'; end if;
  elsif tg_table_name = 'chat_client_errors' then
    select count(*) into recent from public.chat_client_errors where user_id = new.user_id and created_at > now() - interval '1 hour';
    if recent >= 30 then raise exception 'Too many error reports.' using errcode = 'P0001'; end if;
  end if;
  return new;
end; $$;
