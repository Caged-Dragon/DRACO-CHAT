-- Progressive password lockout. Wire it up in Dashboard > Authentication > Hooks >
-- "Password Verification Attempt" -> public.chat_hook_password_verification_attempt
-- Tiers: 3 wrong = 15 min, then 2 wrong = 1 hour, then 1 wrong = 2 hours, then 1 wrong = permanent lock.
-- A correct password (outside a lock) resets everything. Locking never deletes an account.
create or replace function public.chat_hook_password_verification_attempt(event jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := (event ->> 'user_id')::uuid;
  ok boolean := coalesce((event ->> 'valid')::boolean, false);
  s public.chat_login_security%rowtype;
  need int; lvl int; wait interval; mins int; label text;
begin
  insert into public.chat_login_security (user_id) values (uid) on conflict (user_id) do nothing;
  select * into s from public.chat_login_security where user_id = uid for update;

  if s.permanently_locked then
    return jsonb_build_object('decision', 'reject', 'message', 'This account is locked after too many wrong passwords. Please contact support to unlock it.');
  end if;
  if s.locked_until is not null and s.locked_until > now() then
    mins := greatest(1, ceil(extract(epoch from (s.locked_until - now())) / 60)::int);
    return jsonb_build_object('decision', 'reject', 'message',
      'Too many wrong passwords. Try again in ' || mins || case when mins = 1 then ' minute.' else ' minutes.' end);
  end if;

  if ok then
    update public.chat_login_security set failed_count = 0, lock_level = 0, locked_until = null, updated_at = now() where user_id = uid;
    return jsonb_build_object('decision', 'continue');
  end if;

  s.failed_count := s.failed_count + 1;
  need := case s.lock_level when 0 then 3 when 1 then 2 else 1 end;
  if s.failed_count < need then
    update public.chat_login_security set failed_count = s.failed_count, last_failed_at = now(), updated_at = now() where user_id = uid;
    return jsonb_build_object('decision', 'continue');
  end if;

  lvl := s.lock_level + 1;
  if lvl >= 4 then
    update public.chat_login_security set failed_count = 0, lock_level = 4, locked_until = null, permanently_locked = true,
      locked_at = now(), last_failed_at = now(), updated_at = now() where user_id = uid;
    return jsonb_build_object('decision', 'reject', 'message', 'This account is now locked after too many wrong passwords. Please contact support to unlock it.');
  end if;
  wait := case lvl when 1 then interval '15 minutes' when 2 then interval '1 hour' else interval '2 hours' end;
  label := case lvl when 1 then '15 minutes' when 2 then '1 hour' else '2 hours' end;
  update public.chat_login_security set failed_count = 0, lock_level = lvl, locked_until = now() + wait,
    locked_at = now(), last_failed_at = now(), updated_at = now() where user_id = uid;
  return jsonb_build_object('decision', 'reject', 'message', 'Too many wrong passwords. This account is locked for ' || label || '.');
end; $$;
revoke execute on function public.chat_hook_password_verification_attempt(jsonb) from public, anon, authenticated;
grant execute on function public.chat_hook_password_verification_attempt(jsonb) to supabase_auth_admin;

create or replace function public.chat_admin_list_locked_accounts()
returns table (user_id uuid, username text, lock_level integer, locked_until timestamptz, permanently_locked boolean, locked_at timestamptz, last_failed_at timestamptz)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not chat_private.chat_is_admin((select auth.uid())) then raise exception 'Not authorized' using errcode = '42501'; end if;
