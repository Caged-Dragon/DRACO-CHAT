create or replace function public.chat_admin_list_reports(p_status text default 'open', p_limit integer default 100)
returns table (id uuid, created_at timestamptz, reason text, status text, admin_note text, reviewed_at timestamptz,
  reporter_id uuid, reporter_username text, reported_id uuid, reported_username text, reported_suspended boolean,
  reports_against_total bigint, message_content text, message_attachment text, message_created_at timestamptz)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not chat_private.chat_is_admin((select auth.uid())) then raise exception 'Not authorized' using errcode = '42501'; end if;
  return query
  select r.id, r.created_at, r.reason, coalesce(rv.status, 'open'), rv.note, rv.reviewed_at,
         r.reporter_id, rp.username, r.reported_id, rd.username, rd.suspended_at is not null,
         (select count(*) from public.chat_reports x where x.reported_id = r.reported_id),
         m.content, coalesce(m.attachment_name, m.attachment_type), m.created_at
  from public.chat_reports r
  join public.chat_profiles rp on rp.id = r.reporter_id
  join public.chat_profiles rd on rd.id = r.reported_id
  left join public.chat_report_reviews rv on rv.report_id = r.id
  left join public.chat_messages m on m.id = r.message_id
  where p_status = 'all' or coalesce(rv.status, 'open') = p_status
  order by r.created_at desc
