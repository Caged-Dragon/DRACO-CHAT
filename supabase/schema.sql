create or replace function chat_private.chat_guard_friendship_update()
returns trigger language plpgsql set search_path = '' as $$
begin
  if auth.uid() is null then return new; end if;
  if new.requester_id is distinct from old.requester_id or new.addressee_id is distinct from old.addressee_id
     or new.created_at is distinct from old.created_at then
    raise exception 'Only the status of a friendship can be changed';
  end if;
  if old.status = 'accepted' and new.status <> 'accepted' then
    raise exception 'An accepted friendship cannot be reverted';
  end if;
  return new;
end; $$;
drop trigger if exists chat_guard_friendship_update on public.chat_friendships;
create trigger chat_guard_friendship_update before update on public.chat_friendships
  for each row execute function chat_private.chat_guard_friendship_update();

