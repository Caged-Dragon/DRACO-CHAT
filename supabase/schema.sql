create or replace function chat_private.chat_create_profile(p_user uuid, p_email text, p_meta jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare base_username text; final_username text; attempts int := 0;
begin
  base_username := left(regexp_replace(coalesce(p_meta->>'username', p_meta->>'user_name', p_meta->>'full_name',
    split_part(coalesce(p_email, ''), '@', 1), ''), '[^a-zA-Z0-9_]', '', 'g'), 20);
  if base_username is null or base_username = '' then base_username := 'user';
  elsif char_length(base_username) < 3 then base_username := 'user' || base_username; end if;
  final_username := base_username;
  loop
    begin
      insert into public.chat_profiles (id, username, email) values (p_user, final_username, coalesce(p_email, ''));
      exit;
    exception when unique_violation then
      if exists (select 1 from public.chat_profiles where id = p_user) then exit; end if;
      attempts := attempts + 1;
      if attempts > 20 then final_username := 'user' || substr(replace(p_user::text, '-', ''), 1, 12);
      else final_username := left(base_username, 15) || floor(random() * 9000 + 1000)::int::text; end if;
    end;
  end loop;
end; $$;
revoke execute on function chat_private.chat_create_profile(uuid, text, jsonb) from public, anon, authenticated;

create or replace function public.chat_ensure_profile()
returns void language plpgsql security definer set search_path = '' as $$
declare uid uuid := (select auth.uid()); u record;
begin
  if uid is null then raise exception 'Not signed in' using errcode = '42501'; end if;
  if exists (select 1 from public.chat_profiles where id = uid) then return; end if;
  select a.email, a.raw_user_meta_data into u from auth.users a where a.id = uid;
  if not found then return; end if;
  perform chat_private.chat_create_profile(uid, u.email, coalesce(u.raw_user_meta_data, '{}'::jsonb));
end; $$;
revoke execute on function public.chat_ensure_profile() from public, anon;
grant execute on function public.chat_ensure_profile() to authenticated;

