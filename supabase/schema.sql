create or replace function public.chat_admin_review_report(p_report_id uuid, p_status text, p_note text default null, p_suspend boolean default null)
returns void language plpgsql security definer set search_path = '' as $$
declare target uuid;
begin
  if not chat_private.chat_is_admin((select auth.uid())) then raise exception 'Not authorized' using errcode = '42501'; end if;
  if p_status not in ('resolved', 'dismissed') then raise exception 'Status must be resolved or dismissed'; end if;
  select r.reported_id into target from public.chat_reports r where r.id = p_report_id;
  if target is null then raise exception 'Report not found'; end if;
  insert into public.chat_report_reviews (report_id, status, note, reviewed_by, reviewed_at)
  values (p_report_id, p_status, nullif(btrim(p_note), ''), (select auth.uid()), now())
  on conflict (report_id) do update set status = excluded.status, note = excluded.note, reviewed_by = excluded.reviewed_by, reviewed_at = excluded.reviewed_at;
  if p_suspend is not null then
    if chat_private.chat_is_admin(target) then raise exception 'Admins cannot be suspended here'; end if;
    update public.chat_profiles set suspended_at = case when p_suspend then now() else null end where id = target;
  end if;
end; $$;
